import { performance } from 'node:perf_hooks';
import { pollNewPages, type TaskEnvelope } from '@ai-redfish/jev-browser-core';

export interface ObservationOptions {
  forModel?: boolean;
  viewportOnly?: boolean;
  maxElements?: number;
  filter?: string;
  roles?: string[];
}

export interface PostProcessingOptions {
  includeObservation?: boolean;
  followNewTab?: boolean;
  detectNewTabs?: boolean;
  observationOptions?: ObservationOptions;
}

export interface PageInfo {
  pageId: string;
  url?: string;
  title?: string;
}

export interface PostProcessingPorts {
  pages(): Promise<PageInfo[]>;
  selectPage(pageId: string): Promise<unknown>;
  snapshot(opts: ObservationOptions): Promise<unknown>;
}

/** Omitted options preserve legacy behavior unless fast mode was explicitly enabled. */
export function resolvePostProcessing(opts: PostProcessingOptions, fastMode = false) {
  return {
    includeObservation: opts.includeObservation ?? !fastMode,
    followNewTab: opts.followNewTab ?? !fastMode,
    // Explicit following in fast mode opts back into detection, unless explicitly disabled.
    detectNewTabs: opts.detectNewTabs ?? (!fastMode || opts.followNewTab === true),
    observationOptions: { viewportOnly: true, maxElements: 150, ...opts.observationOptions },
  };
}

/** Recursively account for clicks hidden in branch/forEach and actions generated by goal. */
export function stepsMayOpenTab(steps: unknown): boolean {
  if (!Array.isArray(steps)) return false;
  return steps.some((step) => {
    if (typeof step === 'string') return /^\s*(click|goal|evaluate|press)\s*:/.test(step);
    if (!step || typeof step !== 'object') return false;
    const s = step as { kind?: string; action?: string; then?: unknown; body?: unknown };
    return s.kind === 'goal' || ['click', 'evaluate', 'press'].includes(s.action ?? '') ||
      stepsMayOpenTab(s.then) || stepsMayOpenTab(s.body);
  });
}

/** Best-effort metadata must never replace a settled task result or cause a task replay. */
export async function executeWithPostProcessing(
  steps: unknown,
  execute: () => Promise<TaskEnvelope>,
  ports: PostProcessingPorts,
  opts: PostProcessingOptions = {},
  fastMode = false,
): Promise<Record<string, unknown>> {
  const settings = resolvePostProcessing(opts, fastMode);
  const started = performance.now();
  let trackingMs = 0;
  let observationMs = 0;
  let before: PageInfo[] | undefined;
  if (settings.detectNewTabs) {
    const t = performance.now();
    try { before = await ports.pages(); } catch { /* No reliable baseline: do not misidentify existing pages. */ }
    trackingMs += performance.now() - t;
  }
  const taskStarted = performance.now();
  const env = await execute();
  const taskWaitMs = performance.now() - taskStarted;
  const payload: Record<string, unknown> = { ...env };
  if (before) {
    const t = performance.now();
    try {
      const opened = await pollNewPages(before, ports.pages, {
        waitMs: settings.followNewTab && stepsMayOpenTab(steps) ? 700 : 0,
      });
      if (opened.length > 0) {
        payload.openedPages = opened;
        if (settings.followNewTab) {
          const newest = opened[opened.length - 1]!;
          try {
            await ports.selectPage(newest.pageId);
            payload.followedPageId = newest.pageId;
          } catch { /* Report opened pages, but never claim a failed page selection succeeded. */ }
        }
      }
    } catch { /* Task outcome remains available even when page discovery fails. */ }
    trackingMs += performance.now() - t;
  }
  // Observe after selecting the new page; do not race these operations.
  if (settings.includeObservation) {
    const t = performance.now();
    try { payload.afterObservation = await ports.snapshot(settings.observationOptions); } catch { /* Best effort. */ }
    observationMs = performance.now() - t;
  }
  payload.mcpMetrics = {
    taskWaitMs: Math.round(taskWaitMs),
    pageTrackingMs: Math.round(trackingMs),
    observationMs: Math.round(observationMs),
    totalMs: Math.round(performance.now() - started),
  };
  return payload;
}

/** Short local tasks are checked early; long tasks back off to the legacy 500ms interval. */
export async function waitForApiTask(
  getTask: (taskId: string) => Promise<{ envelope: TaskEnvelope }>,
  initial: TaskEnvelope,
  clock: { now(): number; sleep(ms: number): Promise<void> } = {
    now: () => performance.now(),
    sleep: (ms) => new Promise((resolve) => setTimeout(resolve, ms)),
  },
): Promise<TaskEnvelope> {
  const deadline = clock.now() + 30 * 60_000;
  let env = initial;
  let interval = 100;
  while (true) {
    if (env.status === 'paused' || ['done', 'failed', 'expired', 'cancelled'].includes(env.status)) return env;
    if (clock.now() >= deadline) throw new Error('等待任务超时');
    env = (await getTask(initial.taskId)).envelope;
    if (env.status === 'paused' || ['done', 'failed', 'expired', 'cancelled'].includes(env.status)) return env;
    const remaining = deadline - clock.now();
    if (remaining <= 0) throw new Error('等待任务超时');
    await clock.sleep(Math.min(interval, remaining));
    interval = Math.min(interval * 2, 500);
  }
}
